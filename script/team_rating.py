def get_team(name: str) -> dict:

    if name not in TEAMS:
        raise ValueError(f"Team '{name}' not found in the dataset.")
    
    return TEAMS[name]

def get_group(group: str) -> dict:
    group = group.upper()
    return {name: data for name, data in TEAMS.items() if data['group'] == group}

def elo_win_probability(elo1: int, elo2: int) -> float:
    """Calculate the probability of team 1 winning against team 2 based on their ELO ratings."""
    return 1 / (1 + 10 ** ((elo2 - elo1) / 400))

def elo_update(ro:int, p: float) -> float:
    rn = ro + p
    return rn

def points_changes(k:int, total_goal:int, goal:int, winner:float, elo1:int, elo2:int) -> float:
    if goal < 3:
        G = total_goal/goal
    else:
        G = (11 + total_goal) / goal
    
    We = elo_win_probability(elo1, elo2)
    p = k * G * (winner - We)
    return p

